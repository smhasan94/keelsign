/// Why an index could not be parsed.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ParseError {
    /// The index does not start with [`MAGIC`].
    BadMagic,
    /// The header names a format version other than [`VERSION`].
    UnsupportedVersion(u16),
    /// A case name is not UTF-8.
    BadName,
    /// A case has a `pq_alg` byte other than 0..=3.
    UnknownAlgorithm(u8),
    /// A case has an expectation code outside [`Expect::ALL`].
    BadExpectation(u8),
    /// The input ends inside a header or a case.
    Truncated,
    /// Bytes remain after the declared number of cases.
    TrailingBytes,
}

/// One case of the index, borrowing from it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Case<'a> {
    /// The MANIFEST.json name of the image.
    pub name: &'a str,
    /// The algorithm of the image's post-quantum key, if it has one.
    pub algorithm: Option<Algorithm>,
    /// The image's post-quantum public key (empty without one).
    pub public_key: &'a [u8],
    /// The expected verdicts with the `ml-dsa` feature under [`Policy::ClassicalOnly`],
    /// [`Policy::PqOnly`] and [`Policy::Hybrid`], in [`Policy::ALL`] order.
    pub expect: [Expect; 3],
    /// The same without the `ml-dsa` feature (SHA-44).
    pub expect_without_ml_dsa: [Expect; 3],
}

impl Case<'_> {
    /// The expected verdict under `policy`, with the `ml-dsa` feature
    /// (`ml_dsa_enabled`) or without it.
    pub fn expect(&self, policy: Policy, ml_dsa_enabled: bool) -> Option<Expect> {
        let at = Policy::ALL.iter().position(|p| *p == policy)?;
        let set = if ml_dsa_enabled {
            &self.expect
        } else {
            &self.expect_without_ml_dsa
        };
        set.get(at).copied()
    }
}

/// A parsed index header plus the undecoded case bytes.
#[derive(Clone, Copy, Debug)]
pub struct Fixture<'a> {
    /// The number of cases.
    pub count: u16,
    body: &'a [u8],
}

impl<'a> Fixture<'a> {
    /// Parses the index header. The cases are decoded lazily by [`Fixture::cases`].
    pub fn parse(bytes: &'a [u8]) -> Result<Self, ParseError> {
        let mut rest = bytes;
        if take(&mut rest, MAGIC.len())? != MAGIC.as_slice() {
            return Err(ParseError::BadMagic);
        }
        let version = read_u16(&mut rest)?;
        if version != VERSION {
            return Err(ParseError::UnsupportedVersion(version));
        }
        let count = read_u16(&mut rest)?;
        Ok(Self { count, body: rest })
    }

    /// Iterates over the cases. After the first error the iterator ends.
    pub fn cases(&self) -> Cases<'a> {
        Cases {
            rest: self.body,
            remaining: self.count,
            done: false,
        }
    }

    /// The case for image `name`, if the index parses up to it.
    pub fn case(&self, name: &str) -> Option<Case<'a>> {
        self.cases().map_while(Result::ok).find(|c| c.name == name)
    }
}

/// Iterator over the cases of a [`Fixture`].
#[derive(Clone, Debug)]
pub struct Cases<'a> {
    rest: &'a [u8],
    remaining: u16,
    done: bool,
}

impl<'a> Iterator for Cases<'a> {
    type Item = Result<Case<'a>, ParseError>;

    fn next(&mut self) -> Option<Self::Item> {
        if self.done {
            return None;
        }
        if self.remaining == 0 {
            self.done = true;
            return (!self.rest.is_empty()).then_some(Err(ParseError::TrailingBytes));
        }
        self.remaining -= 1;
        let case = parse_case(&mut self.rest);
        if case.is_err() {
            self.done = true;
        }
        Some(case)
    }
}

fn parse_case<'a>(rest: &mut &'a [u8]) -> Result<Case<'a>, ParseError> {
    let name_len = usize::from(read_u8(rest)?);
    let name = core::str::from_utf8(take(rest, name_len)?).map_err(|_| ParseError::BadName)?;
    let algorithm = match read_u8(rest)? {
        0 => None,
        1 => Some(Algorithm::MlDsa44),
        2 => Some(Algorithm::MlDsa65),
        3 => Some(Algorithm::LmsHss),
        other => return Err(ParseError::UnknownAlgorithm(other)),
    };
    let pk_len = usize::from(read_u16(rest)?);
    let public_key = take(rest, pk_len)?;
    let mut expect = [Expect::Ok; 3];
    let mut expect_without_ml_dsa = [Expect::Ok; 3];
    for slot in expect.iter_mut().chain(expect_without_ml_dsa.iter_mut()) {
        let code = read_u8(rest)?;
        *slot = Expect::from_code(code).ok_or(ParseError::BadExpectation(code))?;
    }
    Ok(Case {
        name,
        algorithm,
        public_key,
        expect,
        expect_without_ml_dsa,
    })
}

fn take<'a>(rest: &mut &'a [u8], n: usize) -> Result<&'a [u8], ParseError> {
    let (head, tail) = rest.split_at_checked(n).ok_or(ParseError::Truncated)?;
    *rest = tail;
    Ok(head)
}

fn read_u8(rest: &mut &[u8]) -> Result<u8, ParseError> {
    let [b] = take_array::<1>(rest)?;
    Ok(b)
}

fn read_u16(rest: &mut &[u8]) -> Result<u16, ParseError> {
    take_array(rest).map(u16::from_le_bytes)
}

fn take_array<const N: usize>(rest: &mut &[u8]) -> Result<[u8; N], ParseError> {
    <[u8; N]>::try_from(take(rest, N)?).map_err(|_| ParseError::Truncated)
}

/// The trusted keys of a case: its post-quantum key (if any) and [`ED25519_TEST_KEY`].
pub fn trusted_keys<'a>(case: &Case<'a>) -> Result<TrustedKeys<'a, 1, 1>, KeySetError> {
    let ed25519 = [Ed25519Key {
        public_key: &ED25519_TEST_KEY,
    }];
    match case.algorithm {
        Some(algorithm) => TrustedKeys::with_ed25519(
            &[TrustedKey {
                algorithm,
                public_key: case.public_key,
            }],
            &ed25519,
        ),
        None => TrustedKeys::with_ed25519(&[], &ed25519),
    }
}

/// Where the images are read from: a slot reader per image (an in-memory slice on the
/// host, a `NorFlashReader` over the board flash at the image's address on target).
pub trait Slots {
    /// The reader of one image.
    type Reader<'s>: ImageReader
    where
        Self: 's;

    /// The reader of `image` (the [`IMAGES`] bytes of `name`), or `None` if it cannot be
    /// placed.
    fn slot(&mut self, name: &str, image: &'static [u8]) -> Option<Self::Reader<'_>>;
}

/// [`Slots`] over the images in memory (the `&[u8]` reader).
#[derive(Clone, Copy, Debug, Default)]
pub struct InMemory;

impl Slots for InMemory {
    type Reader<'s> = &'static [u8];

    fn slot(&mut self, _: &str, image: &'static [u8]) -> Option<&'static [u8]> {
        Some(image)
    }
}

/// What went wrong running a cell, besides a verdict mismatch.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CaseError {
    /// The index names an image that is not in [`IMAGES`].
    UnknownImage,
    /// The slot provider could not place the image.
    NoSlot,
    /// The case's key could not be put into a [`TrustedKeys`] set.
    KeySet(KeySetError),
}

/// The result of one cell (one case under one policy).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Outcome {
    /// The policy.
    pub policy: Policy,
    /// The expected verdict.
    pub expect: Expect,
    /// The verdict, or `None` if it is not one of the matrix's, or the cell could not run.
    pub got: Option<Expect>,
    /// Why the cell could not run.
    pub error: Option<CaseError>,
}

impl Outcome {
    /// True when the verdict is the expected one.
    pub fn passed(&self) -> bool {
        self.error.is_none() && self.got == Some(self.expect)
    }

    /// The verdict string, for logs.
    pub fn got_name(&self) -> &'static str {
        match (self.error, self.got) {
            (Some(CaseError::UnknownImage), _) => "UnknownImage",
            (Some(CaseError::NoSlot), _) => "NoSlot",
            (Some(CaseError::KeySet(_)), _) => "KeySetError",
            (None, Some(got)) => got.name(),
            (None, None) => "OtherError",
        }
    }
}

/// Run `case` under `policy`: [`verify_with`]`(backend, ..)` over the image's slot, with
/// [`trusted_keys`], the TLV areas read into `tlv_buf` and the body hashed through
/// `chunk`. The expectation is the case's `ml-dsa`-on or -off cell, as
/// [`Algorithm::is_enabled`] reports for this build.
#[inline(never)]
pub fn run_case<B: Backend + ?Sized, S: Slots>(
    backend: &B,
    slots: &mut S,
    case: &Case<'_>,
    policy: Policy,
    tlv_buf: &mut [u8],
    chunk: &mut [u8],
) -> Outcome {
    let expect = case
        .expect(policy, Algorithm::MlDsa44.is_enabled())
        .unwrap_or(Expect::Ok);
    let fail = |error| Outcome {
        policy,
        expect,
        got: None,
        error: Some(error),
    };
    let Some(data) = image(case.name) else {
        return fail(CaseError::UnknownImage);
    };
    let keys = match trusted_keys(case) {
        Ok(keys) => keys,
        Err(e) => return fail(CaseError::KeySet(e)),
    };
    let Some(mut reader) = slots.slot(case.name, data) else {
        return fail(CaseError::NoSlot);
    };
    let result = verify_with(backend, &mut reader, &keys, policy, tlv_buf, chunk);
    Outcome {
        policy,
        expect,
        got: Expect::of(&result),
        error: None,
    }
}

/// Totals for a whole index run.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Summary {
    /// Cells run (cases × policies).
    pub total: u32,
    /// Cells whose verdict was the expected one.
    pub passed: u32,
}

impl Summary {
    /// True when at least one cell ran and every cell passed.
    pub fn all_passed(&self) -> bool {
        self.total > 0 && self.passed == self.total
    }
}

/// Run every case of the index `bytes` under every policy of [`Policy::ALL`], calling
/// `log` with each outcome.
pub fn run_fixture<B: Backend + ?Sized, S: Slots>(
    bytes: &[u8],
    backend: &B,
    slots: &mut S,
    tlv_buf: &mut [u8],
    chunk: &mut [u8],
    mut log: impl FnMut(&Case<'_>, &Outcome),
) -> Result<Summary, ParseError> {
    let fixture = Fixture::parse(bytes)?;
    let mut summary = Summary::default();
    for case in fixture.cases() {
        let case = case?;
        for &policy in Policy::ALL {
            let outcome = run_case(backend, slots, &case, policy, tlv_buf, chunk);
            log(&case, &outcome);
            summary.total = summary.total.saturating_add(1);
            if outcome.passed() {
                summary.passed = summary.passed.saturating_add(1);
            }
        }
    }
    Ok(summary)
}
