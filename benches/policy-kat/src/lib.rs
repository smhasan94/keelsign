//! The SHA-46 policy matrix as a runnable index, for the host test and the on-target
//! `tests/policy.rs` of both bench projects.
//!
//! `tests/fixtures/images/policy-matrix.bin` is written by `scripts/gen_image_fixtures.py`
//! from the `policy` (and `policy_without_ml_dsa`, SHA-44) cells of `MANIFEST.json`. This
//! crate parses it without allocation or panics, finds each case's image (embedded once
//! with `include_bytes!` in [`IMAGES`]), and runs [`keelsign_verify::verify_with`] on it
//! under every [`Policy`], with the case's post-quantum key and the Ed25519 test key
//! trusted, so the same code checks the matrix on the host and on the boards.
//!
//! Index format "KSPM v2" (lengths little-endian):
//!
//! ```text
//! header:   b"KSPM", u16 version (2), u16 case count
//! per case: u8 name_len, name (UTF-8, the MANIFEST.json name),
//!           u8 pq_alg (0 none, 1 MlDsa44, 2 MlDsa65, 3 LmsHss), u16 pk_len, pk,
//!           u8 expect_classical_only, u8 expect_pq_only, u8 expect_hybrid
//!             (with the `ml-dsa` feature),
//!           u8 expect_classical_only, u8 expect_pq_only, u8 expect_hybrid
//!             (without it)
//! expectation codes: the index of the verdict in `Expect::ALL` (the script's
//!                    POLICY_CODES)
//! ```
//!
//! [`run_case`] picks the set by [`Algorithm::is_enabled`] at run time, so Cargo feature
//! unification cannot make it pick the wrong one.
#![no_std]
#![forbid(unsafe_code)]

